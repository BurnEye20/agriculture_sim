#!/usr/bin/env python3
"""
Generate the telescopic camera mast (3-section linear-actuator lifting column)
of agri_rover from config/camera_mast.yaml.

The generated blocks are spliced between CAMERA_MAST_BEGIN / CAMERA_MAST_END
markers in:
  - models/agri_rover/model.sdf   (Gazebo: links, prismatic joints, row cameras,
                                   JointPositionController linear-motor plugins)
  - urdf/agri_rover.urdf          (RViz / robot_state_publisher TF tree)

Kinematics (joint value 0 = fully retracted):
  base_link --fixed--> mast_stage1_link --prismatic Z--> mast_stage2_link
            --prismatic Z--> mast_stage3_link (camera head: left/right row cameras)
  camera_height = min_camera_height + q(mast_stage2_joint) + q(mast_stage3_joint)

Usage:
  python3 scripts/generate_camera_mast.py
"""

import os
import sys

import yaml

PKG_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG_PATH = os.path.join(PKG_DIR, "config", "camera_mast.yaml")
SDF_PATH = os.path.join(PKG_DIR, "models", "agri_rover", "model.sdf")
URDF_PATH = os.path.join(PKG_DIR, "urdf", "agri_rover.urdf")

BEGIN = "<!-- CAMERA_MAST_BEGIN (auto-generated by scripts/generate_camera_mast.py from config/camera_mast.yaml - do not edit by hand) -->"
END = "<!-- CAMERA_MAST_END -->"


def f(v: float) -> str:
    return f"{v:.4f}".rstrip("0").rstrip(".") if abs(v) > 1e-9 else "0"


def load_geometry():
    with open(CONFIG_PATH, "r") as fh:
        c = yaml.safe_load(fh)["camera_mast"]

    deck = float(c["deck_top_z"])
    h_min = float(c["min_camera_height"])
    h_max = float(c["max_camera_height"])
    h_def = float(c["default_camera_height"])
    cam_below = float(c["camera_below_top"])
    nest = float(c["nest_step"])
    n_moving = 2

    # Retracted: section k bottom = deck + k*nest, all sections share length L.
    # camera_min = deck + 2*nest + L - cam_below
    sec_len = h_min - deck - n_moving * nest + cam_below
    stroke = (h_max - h_min) / n_moving

    errors = []
    if h_max <= h_min:
        errors.append("max_camera_height must be > min_camera_height")
    if sec_len <= 0.15:
        errors.append(f"section length {sec_len:.3f} m too short - raise min_camera_height")
    if sec_len - stroke < float(c["min_overlap"]):
        errors.append(
            f"overlap at full extension {sec_len - stroke:.3f} m < min_overlap "
            f"{c['min_overlap']} m - raise min_camera_height or lower max_camera_height"
        )
    if not (h_min <= h_def <= h_max):
        errors.append("default_camera_height must lie within [min, max]")
    if len(c["section_profiles"]) != 3 or len(c["section_masses"]) != 3:
        errors.append("section_profiles and section_masses need exactly 3 entries")
    if errors:
        for e in errors:
            print(f"[camera_mast] ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    return {
        "x": float(c["mast_x"]),
        "deck": deck,
        "L": sec_len,
        "stroke": stroke,
        "nest": nest,
        "cam_z": sec_len - cam_below,  # camera height inside stage3 frame
        "profiles": [tuple(map(float, p)) for p in c["section_profiles"]],
        "masses": [float(m) for m in c["section_masses"]],
        "effort": float(c["actuator_effort"]),
        "speed": float(c["max_speed_per_stage"]),
        "init_q": (h_def - h_min) / n_moving,
        "h_min": h_min,
        "h_max": h_max,
    }


def box_inertia(m, sx, sy, sz):
    return (
        m / 12.0 * (sy * sy + sz * sz),
        m / 12.0 * (sx * sx + sz * sz),
        m / 12.0 * (sx * sx + sy * sy),
    )


# ------------------------------------------------------------------ SDF --------
ALU = """<material>
          <ambient>0.70 0.72 0.75 1</ambient>
          <diffuse>0.80 0.82 0.85 1</diffuse>
          <specular>0.85 0.85 0.85 1</specular>
        </material>"""
CAP = """<material>
          <ambient>0.45 0.47 0.50 1</ambient>
          <diffuse>0.55 0.57 0.60 1</diffuse>
          <specular>0.6 0.6 0.6 1</specular>
        </material>"""
DARK = """<material>
          <ambient>0.10 0.10 0.12 1</ambient>
          <diffuse>0.14 0.14 0.16 1</diffuse>
          <specular>0.4 0.4 0.4 1</specular>
        </material>"""
LENS = """<material>
          <ambient>0.05 0.15 0.25 1</ambient>
          <diffuse>0.10 0.25 0.40 1</diffuse>
          <specular>0.9 0.9 0.9 1</specular>
        </material>"""


def sdf_box_visual(name, pose, size, material):
    return f"""      <visual name="{name}">
        <pose>{pose}</pose>
        <geometry>
          <box>
            <size>{size}</size>
          </box>
        </geometry>
        {material}
      </visual>"""


def sdf_cyl_visual(name, pose, radius, length, material):
    return f"""      <visual name="{name}">
        <pose>{pose}</pose>
        <geometry>
          <cylinder>
            <radius>{f(radius)}</radius>
            <length>{f(length)}</length>
          </cylinder>
        </geometry>
        {material}
      </visual>"""


def sdf_camera_sensor(name, pose, optical_frame, topic_ns):
    return f"""      <sensor name="{name}" type="camera">
        <pose>{pose}</pose>
        <camera>
          <horizontal_fov>1.0472</horizontal_fov>
          <image>
            <width>640</width>
            <height>640</height>
            <format>R8G8B8</format>
          </image>
          <clip>
            <near>0.05</near>
            <far>15.0</far>
          </clip>
          <optical_frame_id>{optical_frame}</optical_frame_id>
          <camera_info_topic>/rover/{topic_ns}/camera_info</camera_info_topic>
        </camera>
        <always_on>1</always_on>
        <update_rate>15</update_rate>
        <visualize>true</visualize>
        <topic>/rover/{topic_ns}/image_raw</topic>
      </sensor>"""


def sdf_stage_link(g, idx):
    L = g["L"]
    px, py = g["profiles"][idx]
    m = g["masses"][idx]
    ixx, iyy, izz = box_inertia(m, px, py, L)
    z0 = g["deck"] + idx * g["nest"]
    name = f"mast_stage{idx + 1}_link"
    parts = [
        f"""    <link name="{name}">
      <pose>{f(g['x'])} 0 {f(z0)} 0 0 0</pose>
      <inertial>
        <pose>0 0 {f(L / 2)} 0 0 0</pose>
        <mass>{f(m)}</mass>
        <inertia>
          <ixx>{ixx:.6f}</ixx>
          <ixy>0</ixy>
          <ixz>0</ixz>
          <iyy>{iyy:.6f}</iyy>
          <iyz>0</iyz>
          <izz>{izz:.6f}</izz>
        </inertia>
      </inertial>
      <collision name="section_collision">
        <pose>0 0 {f(L / 2)} 0 0 0</pose>
        <geometry>
          <box>
            <size>{f(px)} {f(py)} {f(L)}</size>
          </box>
        </geometry>
      </collision>""",
        sdf_box_visual("section_visual", f"0 0 {f(L / 2)} 0 0 0", f"{f(px)} {f(py)} {f(L)}", ALU),
        # Darker collar at the top of each section (as on real lifting columns)
        sdf_box_visual(
            "top_collar_visual",
            f"0 0 {f(L - 0.008)} 0 0 0",
            f"{f(px + 0.004)} {f(py + 0.004)} 0.016",
            CAP,
        ),
    ]
    if idx == 0:
        # Mounting flange + linear motor drive housing on the deck
        parts.append(
            sdf_box_visual("deck_flange_visual", "0 0 0.008 0 0 0", f"{f(px + 0.05)} {f(py + 0.05)} 0.016", DARK)
        )
        parts.append(
            sdf_box_visual(
                "linear_motor_housing_visual",
                f"{f(-(px / 2 + 0.03))} 0 0.075 0 0 0",
                "0.05 0.06 0.13",
                DARK,
            )
        )
    if idx == 2:
        cz = g["cam_z"]
        parts += [
            # Camera-head collision (cross-bracket + both cameras)
            f"""      <collision name="camera_head_collision">
        <pose>0 0 {f(cz)} 0 0 0</pose>
        <geometry>
          <box>
            <size>0.06 0.24 0.06</size>
          </box>
        </geometry>
      </collision>""",
            sdf_box_visual("top_plate_visual", f"0 0 {f(L + 0.005)} 0 0 0", f"{f(px + 0.01)} {f(py + 0.01)} 0.010", DARK),
            sdf_cyl_visual(
                "gnss_disk_visual",
                f"0 0 {f(L + 0.0275)} 0 0 0",
                0.085,
                0.035,
                """<material>
          <ambient>0.15 0.16 0.18 1</ambient>
          <diffuse>0.20 0.22 0.24 1</diffuse>
          <specular>0.3 0.3 0.3 1</specular>
        </material>""",
            ),
            sdf_cyl_visual("camera_mount_bar_visual", f"0 0 {f(cz)} 1.5707963 0 0", 0.010, 0.20, DARK),
            sdf_box_visual("left_camera_body_visual", f"0 0.075 {f(cz)} 0 0 1.5707963", "0.045 0.055 0.045", DARK),
            sdf_cyl_visual("left_camera_lens_visual", f"0 0.102 {f(cz)} 1.5707963 0 0", 0.016, 0.015, LENS),
            sdf_box_visual("right_camera_body_visual", f"0 -0.075 {f(cz)} 0 0 -1.5707963", "0.045 0.055 0.045", DARK),
            sdf_cyl_visual("right_camera_lens_visual", f"0 -0.102 {f(cz)} 1.5707963 0 0", 0.016, 0.015, LENS),
            "      <!-- LEFT ROW CAMERA SENSOR (looking +Y_rover at the left strawberry row) -->",
            sdf_camera_sensor("left_row_camera", f"0 0.105 {f(cz)} 0 0 1.5707963", "left_camera_optical_link", "left_camera"),
            "      <!-- RIGHT ROW CAMERA SENSOR (looking -Y_rover at the right strawberry row) -->",
            sdf_camera_sensor("right_row_camera", f"0 -0.105 {f(cz)} 0 0 -1.5707963", "right_camera_optical_link", "right_camera"),
        ]
    parts.append("    </link>")
    return "\n".join(parts)


def sdf_prismatic(g, name, parent, child):
    return f"""    <joint name="{name}" type="prismatic">
      <parent>{parent}</parent>
      <child>{child}</child>
      <axis>
        <xyz>0 0 1</xyz>
        <limit>
          <lower>0</lower>
          <upper>{g['stroke']:.4f}</upper>
          <effort>{f(g['effort'])}</effort>
          <velocity>{f(g['speed'])}</velocity>
        </limit>
        <dynamics>
          <damping>30.0</damping>
          <friction>2.0</friction>
        </dynamics>
      </axis>
    </joint>"""


def sdf_motor_plugin(g, joint, stage):
    return f"""    <plugin filename="gz-sim-joint-position-controller-system" name="gz::sim::systems::JointPositionController">
      <joint_name>{joint}</joint_name>
      <topic>/model/agri_rover/camera_mast/{stage}_cmd</topic>
      <use_velocity_commands>true</use_velocity_commands>
      <cmd_max>{f(g['speed'])}</cmd_max>
      <cmd_min>{f(-g['speed'])}</cmd_min>
      <initial_position>{g['init_q']:.4f}</initial_position>
    </plugin>"""


def build_sdf(g):
    return "\n\n".join(
        [
            f"    <!-- TELESCOPIC CAMERA MAST - 3-section linear-actuator lifting column."
            f" Camera height {g['h_min']:.2f} m (retracted) .. {g['h_max']:.2f} m (extended),"
            f" section length {g['L']:.3f} m, stroke {g['stroke']:.3f} m per stage -->",
            sdf_stage_link(g, 0),
            sdf_stage_link(g, 1),
            sdf_stage_link(g, 2),
            """    <joint name="camera_mast_base_joint" type="fixed">
      <parent>base_link</parent>
      <child>mast_stage1_link</child>
    </joint>""",
            sdf_prismatic(g, "mast_stage2_joint", "mast_stage1_link", "mast_stage2_link"),
            sdf_prismatic(g, "mast_stage3_joint", "mast_stage2_link", "mast_stage3_link"),
            "    <!-- Linear motors: position-controlled with speed limit (cmd topics bridged from /camera_mast/stageN_cmd) -->",
            sdf_motor_plugin(g, "mast_stage2_joint", "stage2"),
            sdf_motor_plugin(g, "mast_stage3_joint", "stage3"),
        ]
    )


# ----------------------------------------------------------------- URDF --------
def urdf_box(xyz, size, material, rpy="0 0 0"):
    return f"""    <visual>
      <origin xyz="{xyz}" rpy="{rpy}"/>
      <geometry>
        <box size="{size}"/>
      </geometry>
      <material name="{material}"/>
    </visual>"""


def urdf_cyl(xyz, radius, length, material, rpy="0 0 0"):
    return f"""    <visual>
      <origin xyz="{xyz}" rpy="{rpy}"/>
      <geometry>
        <cylinder radius="{f(radius)}" length="{f(length)}"/>
      </geometry>
      <material name="{material}"/>
    </visual>"""


def urdf_stage_link(g, idx):
    L = g["L"]
    px, py = g["profiles"][idx]
    m = g["masses"][idx]
    ixx, iyy, izz = box_inertia(m, px, py, L)
    vis = [
        urdf_box(f"0 0 {f(L / 2)}", f"{f(px)} {f(py)} {f(L)}", "silver"),
        urdf_box(f"0 0 {f(L - 0.008)}", f"{f(px + 0.004)} {f(py + 0.004)} 0.016", "dark_gray"),
    ]
    if idx == 0:
        vis.append(urdf_box("0 0 0.008", f"{f(px + 0.05)} {f(py + 0.05)} 0.016", "dark_gray"))
        vis.append(urdf_box(f"{f(-(px / 2 + 0.03))} 0 0.075", "0.05 0.06 0.13", "dark_gray"))
    if idx == 2:
        cz = g["cam_z"]
        vis.append(urdf_box(f"0 0 {f(L + 0.005)}", f"{f(px + 0.01)} {f(py + 0.01)} 0.010", "dark_gray"))
        vis.append(urdf_cyl(f"0 0 {f(L + 0.0275)}", 0.085, 0.035, "charcoal"))
        vis.append(urdf_cyl(f"0 0 {f(cz)}", 0.010, 0.20, "dark_gray", rpy="1.5707963 0 0"))
    return f"""  <link name="mast_stage{idx + 1}_link">
    <inertial>
      <origin xyz="0 0 {f(L / 2)}" rpy="0 0 0"/>
      <mass value="{f(m)}"/>
      <inertia ixx="{ixx:.6f}" ixy="0" ixz="0" iyy="{iyy:.6f}" iyz="0" izz="{izz:.6f}"/>
    </inertial>
{chr(10).join(vis)}
  </link>"""


def urdf_camera(side, y_sign):
    yaw = "1.5707963" if y_sign > 0 else "-1.5707963"
    label = "Left Camera Link (Facing +Y -> Left Row)" if y_sign > 0 else "Right Camera Link (Facing -Y -> Right Row)"
    return f"""  <!-- {label} -->
  <link name="{side}_camera_link">
    <visual>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry>
        <box size="0.045 0.055 0.045"/>
      </geometry>
      <material name="dark_gray"/>
    </visual>
    <visual>
      <origin xyz="0.027 0 0" rpy="0 1.5707963 0"/>
      <geometry>
        <cylinder radius="0.016" length="0.015"/>
      </geometry>
      <material name="lens_blue"/>
    </visual>
  </link>

  <joint name="{side}_camera_joint" type="fixed">
    <parent link="mast_stage3_link"/>
    <child link="{side}_camera_link"/>
    <origin xyz="0 {f(0.075 * y_sign)} {{CAM_Z}}" rpy="0 0 {yaw}"/>
  </joint>

  <link name="{side}_camera_optical_link"/>
  <joint name="{side}_camera_optical_joint" type="fixed">
    <parent link="{side}_camera_link"/>
    <child link="{side}_camera_optical_link"/>
    <origin xyz="0.03 0 0" rpy="-1.5707963 0 -1.5707963"/>
  </joint>"""


def urdf_prismatic(g, name, parent, child, z):
    return f"""  <joint name="{name}" type="prismatic">
    <parent link="{parent}"/>
    <child link="{child}"/>
    <origin xyz="0 0 {f(z)}" rpy="0 0 0"/>
    <axis xyz="0 0 1"/>
    <limit lower="0" upper="{g['stroke']:.4f}" effort="{f(g['effort'])}" velocity="{f(g['speed'])}"/>
  </joint>"""


def build_urdf(g):
    cam_z = f(g["cam_z"])
    return "\n\n".join(
        [
            f"  <!-- TELESCOPIC CAMERA MAST - 3-section linear-actuator lifting column."
            f" Camera height {g['h_min']:.2f} m (retracted) .. {g['h_max']:.2f} m (extended) -->",
            urdf_stage_link(g, 0),
            f"""  <joint name="camera_mast_base_joint" type="fixed">
    <parent link="base_link"/>
    <child link="mast_stage1_link"/>
    <origin xyz="{f(g['x'])} 0 {f(g['deck'])}" rpy="0 0 0"/>
  </joint>""",
            urdf_stage_link(g, 1),
            urdf_prismatic(g, "mast_stage2_joint", "mast_stage1_link", "mast_stage2_link", g["nest"]),
            urdf_stage_link(g, 2),
            urdf_prismatic(g, "mast_stage3_joint", "mast_stage2_link", "mast_stage3_link", g["nest"]),
            urdf_camera("left", +1).replace("{CAM_Z}", cam_z),
            urdf_camera("right", -1).replace("{CAM_Z}", cam_z),
        ]
    )


# --------------------------------------------------------------- splice --------
def splice(path, block, indent):
    with open(path, "r") as fh:
        text = fh.read()
    b = text.find("<!-- CAMERA_MAST_BEGIN")
    e = text.find(END)
    if b < 0 or e < 0:
        print(f"[camera_mast] ERROR: markers not found in {path}", file=sys.stderr)
        sys.exit(1)
    line_start = text.rfind("\n", 0, b) + 1
    new = text[:line_start] + indent + BEGIN + "\n" + block + "\n" + indent + text[e:]
    with open(path, "w") as fh:
        fh.write(new)


def main():
    g = load_geometry()
    urdf_block = build_urdf(g)
    # The launch file passes the URDF text as a parameter value, which ROS 2 launch
    # parses as YAML - a ": " anywhere in it would turn it into a YAML mapping.
    if ": " in urdf_block:
        print("[camera_mast] ERROR: generated URDF contains ': ' (breaks launch YAML parsing)", file=sys.stderr)
        sys.exit(1)
    splice(SDF_PATH, build_sdf(g), "    ")
    splice(URDF_PATH, urdf_block, "  ")
    print(
        f"[camera_mast] Generated mast: camera height {g['h_min']:.3f} .. {g['h_max']:.3f} m | "
        f"section length {g['L']:.3f} m | stroke/stage {g['stroke']:.3f} m | "
        f"overlap at full extension {g['L'] - g['stroke']:.3f} m | "
        f"startup joint position {g['init_q']:.3f} m"
    )
    print(f"[camera_mast] Updated {SDF_PATH}\n[camera_mast] Updated {URDF_PATH}")


if __name__ == "__main__":
    main()
